"""Write the D1 migration that moves stored answer letters from the old shuffled option order
to the ABIM (alphabetical / numeric) order.

    python3 scripts/qbank_remap_sql.py   ->  qbank/migrations/0004_abim_order.sql

Run once, for the questions that were live before the switch (Nov 2026). Tables touched:
test_items.choice, test_items.first_choice, q_stats.choice. `correct` values do not change.
"""
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))
import qbank_build as qb  # noqa: E402

OUT = ROOT / "qbank" / "migrations" / "0004_abim_order.sql"


def main():
    maps = {}
    for f in sorted(qb.QDIR.glob("*.yml")):
        for q in yaml.safe_load(f.read_text(encoding="utf-8")) or []:
            old = qb.legacy_shuffle_order(q)
            new = qb.abim_order(q)
            old_letter = {k: qb.LETTERS[i] for i, k in enumerate(old)}
            new_letter = {k: qb.LETTERS[i] for i, k in enumerate(new)}
            m = {old_letter[k]: new_letter[k] for k in old}
            if any(a != b for a, b in m.items()):
                maps[q["id"]] = m

    lines = ["-- Move stored answer letters to ABIM option order (generated by scripts/qbank_remap_sql.py)",
             "CREATE TABLE IF NOT EXISTS _letter_map (qid TEXT NOT NULL, old TEXT NOT NULL, new TEXT NOT NULL, PRIMARY KEY (qid, old));",
             "DELETE FROM _letter_map;"]
    rows = [f"('{qid}','{o}','{n}')" for qid, m in sorted(maps.items()) for o, n in m.items()]
    for i in range(0, len(rows), 200):
        lines.append("INSERT INTO _letter_map (qid, old, new) VALUES " + ",".join(rows[i:i + 200]) + ";")
    lines += [
        "UPDATE test_items SET choice = (SELECT new FROM _letter_map m WHERE m.qid = test_items.qid AND m.old = test_items.choice)",
        "  WHERE choice IS NOT NULL AND EXISTS (SELECT 1 FROM _letter_map m WHERE m.qid = test_items.qid AND m.old = test_items.choice);",
        "UPDATE test_items SET first_choice = (SELECT new FROM _letter_map m WHERE m.qid = test_items.qid AND m.old = test_items.first_choice)",
        "  WHERE first_choice IS NOT NULL AND EXISTS (SELECT 1 FROM _letter_map m WHERE m.qid = test_items.qid AND m.old = test_items.first_choice);",
        # q_stats has PRIMARY KEY (qid, choice): rebuild instead of updating in place
        "CREATE TABLE _q_stats_new (qid TEXT NOT NULL, choice TEXT NOT NULL, n INTEGER NOT NULL DEFAULT 0, PRIMARY KEY (qid, choice));",
        "INSERT INTO _q_stats_new (qid, choice, n) SELECT s.qid, COALESCE(m.new, s.choice), SUM(s.n) FROM q_stats s",
        "  LEFT JOIN _letter_map m ON m.qid = s.qid AND m.old = s.choice GROUP BY s.qid, COALESCE(m.new, s.choice);",
        "DELETE FROM q_stats;",
        "INSERT INTO q_stats (qid, choice, n) SELECT qid, choice, n FROM _q_stats_new;",
        "DROP TABLE _q_stats_new;",
        "DROP TABLE _letter_map;",
    ]
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"{len(maps)} questions remapped -> {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
